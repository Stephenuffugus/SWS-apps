#!/usr/bin/env node
/* ═══════════════════════════════════════════════════════════════════════════
   SWS STUDIO, pull workflow findings onto disk

   The competitor research and the per-app UI audit both ran as background
   workflows, and their results live inside run journals. This lifts them out
   into plain files so the agents doing the actual rebuild, and a human
   reading this in six months, can just open them.

     node design/extract-findings.mjs <runId-or-dir> [<runId-or-dir> ...]

   Writes design/findings/<slug>.research.json, .audit.json, and any
   free-text synthesis it finds, plus an INDEX.md listing what landed.
   ═══════════════════════════════════════════════════════════════════════════ */

import { readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join, basename } from 'node:path';

const HERE = dirname(fileURLToPath(import.meta.url));
const OUT = join(HERE, 'findings');
const WORKFLOWS = join(
  process.env.HOME, '.claude', 'projects', '-workspaces-SWS-apps',
  'de49fc52-01a6-49a1-9a8c-9809b594efa2', 'subagents', 'workflows',
);

function resolveDir(arg){
  if (existsSync(join(arg, 'journal.jsonl'))) return arg;
  const direct = join(WORKFLOWS, arg);
  if (existsSync(join(direct, 'journal.jsonl'))) return direct;
  // allow a bare run id that is a prefix of the directory name
  const hit = readdirSync(WORKFLOWS).find((d) => d.includes(arg));
  if (hit && existsSync(join(WORKFLOWS, hit, 'journal.jsonl'))) return join(WORKFLOWS, hit);
  return null;
}

mkdirSync(OUT, { recursive: true });

const landed = { research: [], audit: [], other: [] };

for (const arg of process.argv.slice(2)){
  const dir = resolveDir(arg);
  if (!dir){ console.log(`  !! no journal for "${arg}"`); continue; }

  const entries = readFileSync(join(dir, 'journal.jsonl'), 'utf8')
    .trim().split('\n')
    .map((l) => { try { return JSON.parse(l); } catch { return null; } })
    .filter((e) => e && e.result !== undefined);

  for (const { result } of entries){
    if (result && typeof result === 'object' && result.slug){
      /* Research rows carry `competitors`; audit rows carry `cssClasses`.
         Distinguishing on shape rather than on which run it came from means
         re-running with both ids in either order does the right thing. */
      const kind = result.competitors ? 'research' : result.cssClasses ? 'audit' : null;
      if (!kind){ landed.other.push(result.slug); continue; }
      writeFileSync(join(OUT, `${result.slug}.${kind}.json`), JSON.stringify(result, null, 2));
      landed[kind].push(result.slug);
    } else if (typeof result === 'string' && result.length > 400){
      const name = `synthesis-${basename(dir).slice(0, 12)}.md`;
      writeFileSync(join(OUT, name), result);
      landed.other.push(name);
    } else if (result && typeof result === 'object' && result.synthesis){
      writeFileSync(join(OUT, 'PORTFOLIO-SYNTHESIS.md'), result.synthesis);
      landed.other.push('PORTFOLIO-SYNTHESIS.md');
    }
  }
}

const uniq = (a) => [...new Set(a)].sort();
const index = `# Findings

Generated by \`design/extract-findings.mjs\`. Source of truth for the rebuild.

- \`<slug>.research.json\`, competitors, real user complaints, UX table stakes,
  emotional context and a recommended hue for that app.
- \`<slug>.audit.json\`, that app's DOM shape, CSS class inventory, the markup
  its JS generates at runtime, and its comfort / navigation / accessibility
  defects with file:line.
- \`PORTFOLIO-SYNTHESIS.md\`, the cross-app read: which complaints repeat, what
  the whole portfolio is missing, and the highest-leverage moves.

## Research (${uniq(landed.research).length})
${uniq(landed.research).map((s) => `- ${s}`).join('\n') || '- none yet'}

## Audit (${uniq(landed.audit).length})
${uniq(landed.audit).map((s) => `- ${s}`).join('\n') || '- none yet'}

## Other
${uniq(landed.other).map((s) => `- ${s}`).join('\n') || '- none'}
`;
writeFileSync(join(OUT, 'INDEX.md'), index);

console.log(`research: ${uniq(landed.research).length}  audit: ${uniq(landed.audit).length}  other: ${uniq(landed.other).length}`);
console.log(`→ design/findings/`);
